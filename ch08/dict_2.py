'''
建立一個新字典（說明註解） 
說明 dict() 函式建立字典時，若傳入序列（Iterable），只接受 1 個主要的位置引數 (Positional Argument)
(註解說明：傳入的資料結構最外層必須是一個整體包裹起來的容器）






使用 dict() 將一個「包含 Tuple 元素」的雙層 Tuple 轉換為字典
最外層括號包裹住兩個鍵值對 (('一月','正月'), ('二月','花月'))，傳入單一 Iterable 物件
'''
# =============== dict ================
# 使用 dict(元組或串列) 將一個「包含 Tuple 元素」的雙層 Tuple 轉換為字典 　
dict1 = dict((('一月','正月'),('二月','花月'))) 
# 印出轉換後的字典 dict1，結果為 key-value 形式：{'一月': '正月', '二月': '花月'}
print(dict1) # 輸出結果 {'一月': '正月', '二月': '花月'}
# 使用 dict() 將一個「包含 List 元素」的雙層 List（清單）轉換為字典
# 最外層中括號包裹住兩個鍵值對 [['一月','正月'], ['二月','花月']]，同樣也是傳入單一 Iterable 物件
dict1 = dict([['一月','正月'],['二月','花月']])
# 印出轉換後的字典 dict1，結果同樣為 key-value 形式：{'一月': '正月', '二月': '花月'}
print(dict1) # 輸出結果 {'一月': '正月', '二月': '花月'}
 
# ============= fromkeys ==============
# 使用 dict.fromkeys(元組或串列,預設值) 建立新字典，傳入包含 key 的元組 ('四月', '五月')
dict2 = dict.fromkeys(('四月','五月'))
# 印出字典 dict2 的內容
# 當未指定初始 Value（預設值）時，Python 會自動將所有 Key 的 Value 設為 None
print(dict2)  # 輸出結果 {'四月': None, '五月': None}
 
# 使用 dict.fromkeys() 建立新字典，第一個引數傳入 Key 的串列 ['一月', '四月']
# 第二個引數傳入指定預設值 '端月'，此時所有 Key 都會被賦予相同的 Value ('端月')
dict2 = dict.fromkeys(['一月','四月'],'端月')
 
# 印出字典 dict2 的內容
print(dict2)  # 輸出結果 {'一月': '端月', '四月': '端月'}
 
# =============== keys ================
# 使用 keys() 傳回字典中所有的鍵（Key），回傳型態為 dict_keys 物件
print(dict1.keys()) # 輸出結果 dict_keys(['一月', '二月'])
 
# ============== values ===============
# 使用 values() 傳回字典中所有的值（Value），並用 tuple() 將其轉為元組包裝
print(tuple(dict1.values())) # 輸出結果 ('正月', '花月')
 
# =============== items ===============
# 使用 items() 傳回字典中所有的 (Key, Value) 鍵值對元組，並用 list() 將其轉為清單包裝
print(list(dict1.items())) # 輸出結果 [('一月', '正月'), ('二月', '花月')]
 
# =============== get =================
# 使用 get(key[,value]) 尋找字典中指定鍵 ('三月') 所對應的值；因為鍵不存在且未設定預設值，所以回傳 None（程式不會報錯）
print(dict2.get('三月')) # 輸出結果 None
 
# ============= setdefault =============
# 使用 setdefault(key[,value]) 尋找鍵：
# 1. 若 Key 已存在（如 '一月'），直接傳回原有的 Value ('端月')，後方設定的預設值 '梅月' 被忽略，字典不變
print(dict2.setdefault('一月', '梅月')) # 輸出結果 端月
print(dict2)                           # 輸出結果 {'一月': '端月', '四月': '端月'}
 
# 2. 若 Key 不存在（如 '三月'），會自動將 ('三月': '梅月') 新增至 dict2 中，並回傳設定的新 Value ('梅月')
print(dict2.setdefault('三月', '梅月')) # 輸出結果 梅月
print(dict2)                           # 輸出結果 {'一月': '端月', '四月': '端月', '三月': '梅月'}
 
# ============= pop =============
# 使用 pop(key[,value]) 刪除指定 Key 並傳回其對應的 Value：
# 1. 若刪除的 Key 不存在（如 '10 月'），但有傳入第二個參數預設值 ('NONE')，則不會報錯並傳回該預設值
# dict1 = {'一月': '正月', '二月': '花月'}
print(dict1.pop('10 月', 'NONE')) # NONE
# 2. 刪除指定的 Key（修正：將原本不存在的 '10月' 改為已存在的 '二月'），刪除後傳回 '花月'
print(dict1.pop('二月')) # 花月 
print(dict1)     # 輸出結果 {'一月': '正月'}
 
# ============= popitem =============
# 使用 popitem() 移除並傳回字典中的「最後一筆」鍵值對（Tuple 形式）
# （注意：此處改作用於剛新增過項目的 dict2 示範）
# dict2={'一月': '端月', '四月': '端月', '三月': '梅月'}
print(dict2.popitem()) # 輸出結果 ('三月', '梅月')（dict2 中最新加入的項目被移除）
 
# ============= update =============
# 使用 update() 整合兩個字典：將 dict2 中的所有鍵值對合併至 dict1 中
# 若 Key 已存在（如 '一月'），dict2 的值 ('端月') 會覆蓋 dict1 原本的值 ('正月')
# dict1={'一月': '正月'}
# dict2={'一月': '端月', '四月': '端月'}
dict1.update(dict2)
print(dict1)
# 輸出結果 {'一月': '端月', '四月': '端月'} 
 
# ============= clear =============
# 使用 clear() 清空字典內的所有元素，使其變成空字典
dict1.clear()
print(dict1) # 輸出結果 {}