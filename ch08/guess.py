# 這段程式碼是一個**猜數字（樂透）小遊戲**：電腦會隨機產生 2 個 1 到 7 之間不重複的數字，玩家最多有 3 次機會輸入 2 個數字來猜電腦的解答。
# 從 random 模組中匯入 randint 函式，用來產生指定範圍內的隨機整數
from random import randint
# 建立一個空的集合 (Set) 變數 pc，用來儲存電腦產生的答案（利用集合不重複的特性）
pc = set()
# 當 pc 集合內的元素個數小於 2 個時，持續執行迴圈
while (len(pc) < 2):
    # 產生一個 1 到 7 之間的隨機整數，並加入 pc 集合中 
    # 如果抽到重複的數字，集合會自動忽略，直到湊滿 2 個不重複的數字才會結束迴圈
    pc.add(randint(1, 7))
