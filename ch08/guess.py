# 建立變數 count 並設定初始值為 3，代表玩家最多有 3 次猜題機會
count = 3
# 當 count 大於 0 時（在 Python 中非零數字視為 True），持續執行猜題迴圈
while (count):
    # 建立一個空的集合 you，用來儲存玩家這次輸入的 2 個數字
    you = set()
    # 當玩家輸入的有效數字還不到 2 個時，持續提示輸入
    while (len(you) < 2):
        # 提示玩家輸入數字，使用 f-string 顯示目前是輸入第幾個號碼（1 或 2），並用 int() 轉為整數
        x = int(input (f'請輸入第 {len(you) + 1} 個號碼：'))
        # 檢查玩家輸入的數字是否在 1 到 7 的有效範圍內 (1 <= x <= 7)
        if(x <= 7 and x > 0):
            #若符合範圍則加入 you 集合中（若輸入重複數字，集合長度不會增加，會要求重填）
            you.add(x)
    # 比較電腦答案(pc) 與玩家輸入(you) 是否完全相同(集合比較不看順序，只看元素是否一致）
    if(pc == you):
        # 如果兩者集合相同，印出「答對了」
        print('答對了')
        # 強制跳出最外層的 while 迴圈，提前結束遊戲
        break
    # 若答案不符合，印出「答錯了」
    print('答錯了')
    # 將剩餘次數 count 減 1，繼續進行下一次嘗試，直到 count 扣到 0 為止
    count -= 1