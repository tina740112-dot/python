# 1. 準備一個大箱子（用來裝整張 9 行的乘法表）
big_box = []

# 2. 外層迴圈：代表「被乘數 i」（1 到 9），等於要處理第 1 行到第 9 行
for i in range(1, 10):
    
    # 3. 換新的一行時，拿一個全新的空小盒子（用來裝這一行的 9 個數字）
    s_box = []
    
    # 4. 內層迴圈：代表「乘數 j」（1 到 9），算出這一行的每個答案
    for j in range(1, 10):
        答案 = i * j
        s_box.append(答案)  # 把算好的數字放進小盒子裡
        
    # 5. 這一行的 9 個數字都裝滿後，把小盒子塞進大箱子存起來
    big_box.append(s_box)


# ----------------- 下面是把資料一排一排印出來 -----------------

# 6. 從大箱子裡，一次拿出一盒小盒子（一橫排）
for s_box in big_box:
    
    # 7. 從那盒小盒子裡，一次拿出一個數字
    for num in s_box:
        print(f"{num:2d}", end="  ")  # 印出數字（固定2格寬對齊），後面接空白不換行
        
    print()  # 這盒的 9 個數字印完了，執行純換行，準備印下一盒
    
    
 
  
  